"""Run the 4 official test cases (+ failure scenarios) and write TEST_EVIDENCE.md.

Usage:  python run_tests.py          (all scenarios)
        python run_tests.py TC1 TC3  (only some)

Failures are written down honestly - this script never hides a FAIL.
"""
import sys
from datetime import datetime, timedelta, timezone

from fastapi.testclient import TestClient

from agent.scenarios import run_all
from portal.app import app as portal_app

IST = timezone(timedelta(hours=5, minutes=30))


def to_markdown(results):
    now = datetime.now(IST).strftime("%d %b %Y, %I:%M %p IST")
    official = [r for r in results if r["official"]]
    lines = [
        "# TEST EVIDENCE - Crop Insurance Claim Tracker",
        "",
        f"Generated by `python run_tests.py` on {now}. All data is synthetic.",
        "Each case resets the mock portal, talks to a fresh agent, and checks results against a",
        "direct portal read (not the agent's own claims).",
        "",
        f"**Official cases: {sum(r['passed'] for r in official)}/{len(official)} PASS.  "
        f"All scenarios: {sum(r['passed'] for r in results)}/{len(results)} PASS.**",
        "",
        "| Case | Title | Result |",
        "|---|---|---|",
    ]
    lines += [f"| {r['id']} | {r['title']} | {'PASS' if r['passed'] else '**FAIL**'} |" for r in results]
    for r in results:
        lines += ["", f"## {r['id']} - {r['title']} - {'PASS' if r['passed'] else 'FAIL'}", "",
                  "**Input (farmer):**", ""]
        lines += [f"- `{t}`" for t in r["inputs"]]
        lines += ["", f"**Expected:** {r['expected']}", "", "**Actual (agent replies):**", ""]
        lines += [f"> {t}" + "\n>" for t in r["actual"]]
        lines += ["", "**Checks:**", ""]
        lines += [f"- [{'x' if ch['ok'] else ' '}] {ch['label']}" for ch in r["checks"]]
        if r["error"]:
            lines += ["", f"**Error:** `{r['error']}`"]
        lines += ["", "<details><summary>Evidence log</summary>", "", "```"]
        lines += r["evidence"]
        lines += ["```", "</details>"]
    return "\n".join(lines) + "\n"


def main(only=None):
    with TestClient(portal_app) as http:
        results = run_all(http, only=only)
    with open("TEST_EVIDENCE.md", "w", encoding="utf-8") as f:
        f.write(to_markdown(results))
    for r in results:
        print(f"{r['id']:4} {'PASS' if r['passed'] else 'FAIL'}  {r['title']}")
        for ch in r["checks"]:
            if not ch["ok"]:
                print(f"       x {ch['label']}")
        if r["error"]:
            print(f"       error: {r['error']}")
    print("Wrote TEST_EVIDENCE.md")
    return all(r["passed"] for r in results)


if __name__ == "__main__":
    sys.exit(0 if main(sys.argv[1:] or None) else 1)
